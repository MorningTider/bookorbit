import { mount, flushPromises } from '@vue/test-utils'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import ChapterRuleManager from './ChapterRuleManager.vue'
const mocks = vi.hoisted(() => ({ api: vi.fn() }))
vi.mock('@/lib/api', () => ({ api: mocks.api }))
vi.mock('vue-i18n', () => ({ useI18n: () => ({ t: (key: string) => key }) }))
beforeEach(() => {
  vi.resetAllMocks()
  mocks.api.mockResolvedValue(new Response(JSON.stringify({ sources: [] })))
})
describe('public chapter rule manager', () => {
  it('loads existing definitions and saves JSON through the protected API', async () => {
    const wrapper = mount(ChapterRuleManager)
    await flushPromises()
    expect(mocks.api).toHaveBeenCalledWith('/api/v1/book-sources/chapter-rules')
    await wrapper.find('textarea').setValue('{"sources": []}')
    mocks.api.mockResolvedValueOnce(new Response('{"sources": []}'))
    await wrapper.find('form').trigger('submit')
    await flushPromises()
    expect(mocks.api).toHaveBeenCalledWith('/api/v1/book-sources/chapter-rules', expect.objectContaining({ method: 'PUT', body: '{"sources":[]}' }))
    expect(wrapper.emitted('updated')).toHaveLength(1)
    wrapper.unmount()
  })
  it('keeps invalid JSON local and displays permission failures without reporting success', async () => {
    const wrapper = mount(ChapterRuleManager)
    await flushPromises()
    await wrapper.find('textarea').setValue('bad json')
    await wrapper.find('form').trigger('submit')
    await flushPromises()
    expect(mocks.api).toHaveBeenCalledTimes(1)
    expect(wrapper.find('[role="alert"]').exists()).toBe(true)
    await wrapper.find('textarea').setValue('{"sources": []}')
    mocks.api.mockResolvedValueOnce(new Response('{"message":"Forbidden"}', { status: 403 }))
    await wrapper.find('form').trigger('submit')
    await flushPromises()
    expect(wrapper.find('[role="alert"]').text()).toBe('You do not have permission to perform this action.')
    expect(wrapper.emitted('updated')).toBeUndefined()
    wrapper.unmount()
  })
  it('refuses to overwrite rules after a failed initial load and allows a safe reload', async () => {
    mocks.api.mockResolvedValueOnce(new Response('unavailable', { status: 503 }))
    const wrapper = mount(ChapterRuleManager)
    await flushPromises()
    expect(wrapper.find('textarea').attributes('disabled')).toBeDefined()
    await wrapper.find('form').trigger('submit')
    await flushPromises()
    expect(mocks.api).toHaveBeenCalledTimes(1)
    expect(wrapper.emitted('updated')).toBeUndefined()
    const retry = wrapper.findAll('button').find((button) => button.text() === 'common.retry')!
    expect(retry.exists()).toBe(true)
    await retry.trigger('click')
    await flushPromises()
    expect(wrapper.find('textarea').attributes('disabled')).toBeUndefined()
    expect(mocks.api).toHaveBeenCalledTimes(2)
    wrapper.unmount()
  })
})
